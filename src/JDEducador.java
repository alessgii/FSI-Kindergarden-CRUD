    private void BEducadorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BEducadorActionPerformed
        Educador edu = new Educador(
                TCurp.getText(),
                TNombre.getText(),
                CBSexo.getSelectedItem().toString(),
                TTelefono.getText(),
                TDireccion.getText(),
                CBEstado.getSelectedItem().toString()
        );

        if (edu.borrar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "El educador ha sido eliminado.");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error al eliminar al educador.");
        }
    }//GEN-LAST:event_BEducadorActionPerformed

