    private void BNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BNuevoActionPerformed
        if (BInfantes.isSelected()) {
            JDInfantes di = new JDInfantes(this, true);
            di.obtenerConexion(cnx);
            di.setVisible(true);
            cnx.entablar(Infante.todos, TQuery);
        } else if (BEducadores.isSelected()) {
            JDEducador de = new JDEducador(this, true);
            de.obtenerConexion(cnx);
            de.setVisible(true);
            cnx.entablar(Educador.todos, TQuery);
        } else if (BResponsables.isSelected()) {
            JDResponsable dr = new JDResponsable(this, true);
            dr.obtenerConexion(cnx);
            dr.setVisible(true);
            cnx.entablar(Responsable.todos, TQuery);
        } else if (BBitacora.isSelected()) {
            JDBitacora db = new JDBitacora(this, true);
            db.obtenerConexion(cnx);
            db.setVisible(true);
            cnx.entablar(Bitacora.todos, TQuery);
        }
    }//GEN-LAST:event_BNuevoActionPerformed

    private void BEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BEditarActionPerformed
        if (TQuery.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Primero selecciona un renglón de la tabla para editar.");
            return;
        }
        if (BInfantes.isSelected()) {
            JDInfantes di = new JDInfantes(this, true);
            di.obtenerConexion(cnx);
            di.obtenerInfante(crearInfante());
            di.setVisible(true);
            cnx.entablar(Infante.todos, TQuery);
        } else if (BEducadores.isSelected()) {
            JDEducador de = new JDEducador(this, true);
            de.obtenerConexion(cnx);
            de.obtenerEducador(crearEducador());
            de.setVisible(true);
            cnx.entablar(Educador.todos, TQuery);
        } else if (BResponsables.isSelected()) {
            JDResponsable dr = new JDResponsable(this, true);
            dr.obtenerConexion(cnx);
            dr.obtenerResponsable(crearResponsable());
            dr.setVisible(true);
            cnx.entablar(Responsable.todos, TQuery);
        } else if (BBitacora.isSelected()) {
            JDBitacora db = new JDBitacora(this, true);
            db.obtenerConexion(cnx);
            db.obtenerBitacora(crearBitacora());
            db.setVisible(true);
            cnx.entablar(Bitacora.todos, TQuery);
        }
    }//GEN-LAST:event_BEditarActionPerformed

